@router.post("", response_model=DocumentResponse, status_code=status.HTTP_201_CREATED)
async def upload_document(
    project_id: int,
    file: UploadFile = File(...),
    db: AsyncSession = Depends(get_db),
    current_user: dict = Depends(require_assessor),
) -> DocumentResponse:
    # Verify project exists
    result = await db.execute(select(Project).where(Project.id == project_id))
    if not result.scalar_one_or_none():
        raise HTTPException(status_code=404, detail="Project not found")

    # Validate extension
    suffix = Path(file.filename).suffix.lower()
    if suffix not in ALLOWED_EXTENSIONS:
        raise HTTPException(status_code=400, detail=f"File type not allowed: {suffix}")

    # Read and validate size
    content = await file.read()
    max_bytes = settings.max_upload_size_mb * 1024 * 1024
    if len(content) > max_bytes:
        raise HTTPException(status_code=413, detail=f"File exceeds {settings.max_upload_size_mb}MB limit")

    # Compute hash (duplicate detection)
    file_hash = hashlib.sha256(content).hexdigest()
    existing = await db.execute(
        select(Document).where(Document.project_id == project_id, Document.file_hash == file_hash)
    )
    if existing.scalar_one_or_none():
        raise HTTPException(status_code=409, detail="This file has already been uploaded to this project")

    # Save to disk
    project_upload_dir = Path(settings.upload_dir) / str(project_id)
    project_upload_dir.mkdir(parents=True, exist_ok=True)
    unique_name = f"{uuid.uuid4().hex}{suffix}"
    file_path = project_upload_dir / unique_name
    async with aiofiles.open(file_path, "wb") as f:
        await f.write(content)

    doc = Document(
        project_id=project_id,
        filename=file.filename,
        file_path=str(file_path),
        file_type=_get_file_type(file.filename),
        file_hash=file_hash,
        file_size_bytes=len(content),
        parse_status="pending",
        uploaded_by=current_user["id"],
    )
    db.add(doc)
    await db.commit()
    await db.refresh(doc)

    return doc


@router.get("/download-all")
async def download_all_documents(
    project_id: int,
    db: AsyncSession = Depends(get_db),
    _: dict = Depends(require_viewer),
):
    """Download all documents for a project as a ZIP archive."""
    import io
    import zipfile
    from fastapi.responses import StreamingResponse

    result = await db.execute(
        select(Document).where(Document.project_id == project_id).order_by(Document.filename)
    )
    docs = result.scalars().all()

    if not docs:
        raise HTTPException(status_code=404, detail="No documents found for this project")

    buf = io.BytesIO()
    seen_names: dict[str, int] = {}
    with zipfile.ZipFile(buf, mode="w", compression=zipfile.ZIP_DEFLATED) as zf:
        for doc in docs:
            if not doc.file_path or not Path(doc.file_path).exists():
                continue
            # Deduplicate filenames inside the ZIP
            name = doc.filename or Path(doc.file_path).name
            if name in seen_names:
                seen_names[name] += 1
                stem = Path(name).stem
                suffix = Path(name).suffix
                name = f"{stem} ({seen_names[name]}){suffix}"
            else:
                seen_names[name] = 0
            zf.write(doc.file_path, arcname=name)

    buf.seek(0)
    return StreamingResponse(
        buf,
        media_type="application/zip",
        headers={"Content-Disposition": f"attachment; filename=project-{project_id}-documents.zip"},
    )


@router.get("/{document_id}/download")
async def download_document(
    project_id: int,
    document_id: int,
    db: AsyncSession = Depends(get_db),
    _: dict = Depends(require_viewer),
):
    """Download the original uploaded file."""
    from fastapi.responses import FileResponse as FR
    result = await db.execute(
        select(Document).where(Document.id == document_id, Document.project_id == project_id)
    )
    doc = result.scalar_one_or_none()
    if not doc:
        raise HTTPException(status_code=404, detail="Document not found")
    if not Path(doc.file_path).exists():
        raise HTTPException(status_code=410, detail="File no longer exists on disk")
    return FR(
        path=doc.file_path,
        filename=doc.filename,
        media_type="application/octet-stream",
    )


@router.post("/{document_id}/reparse", response_model=DocumentResponse)
async def reparse_document(
    project_id: int,
    document_id: int,
    db: AsyncSession = Depends(get_db),
    _: dict = Depends(require_assessor),
) -> DocumentResponse:
    """Re-trigger parsing for a failed or stuck document."""
    result = await db.execute(
        select(Document).where(Document.id == document_id, Document.project_id == project_id)
    )
    doc = result.scalar_one_or_none()
    if not doc:
        raise HTTPException(status_code=404, detail="Document not found")

    if not Path(doc.file_path).exists():
        raise HTTPException(status_code=409, detail="File no longer exists on disk — please re-upload")

    # Clear previous error and reset status
    doc.parse_status = "pending"
    doc.parse_error = None
    await db.commit()
    await db.refresh(doc)

    return doc


@router.post("/{document_id}/reindex", response_model=DocumentResponse)
async def reindex_document(
    project_id: int,
    document_id: int,
    db: AsyncSession = Depends(get_db),
    _: dict = Depends(require_assessor),
) -> DocumentResponse:
    """Re-trigger control tagging for a parsed document."""
    result = await db.execute(
        select(Document).where(Document.id == document_id, Document.project_id == project_id)
    )
    doc = result.scalar_one_or_none()
    if not doc:
        raise HTTPException(status_code=404, detail="Document not found")

    if doc.parse_status in ("pending", "processing", "indexing", "queued"):
        raise HTTPException(status_code=409, detail="Document is already being processed or queued")

    if doc.parse_status not in ("complete", "indexed", "index_failed", "failed"):
        raise HTTPException(status_code=409, detail="Document must be fully parsed before indexing")

    doc.parse_status = "pending"
    doc.parse_error = None
    await db.commit()
    await db.refresh(doc)

    return doc


