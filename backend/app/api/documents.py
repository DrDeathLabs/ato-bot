@router.post("/reindex-all")
async def reindex_all_documents(
    project_id: int,
    db: AsyncSession = Depends(get_db),
    _: dict = Depends(require_assessor),
) -> dict:
    """Queue control tagging for all parsed-but-not-indexed documents in the project."""
    result = await db.execute(
        select(Document).where(
            Document.project_id == project_id,
            Document.parse_status.in_(["complete", "indexed", "index_failed"]),
        )
    )
    docs = result.scalars().all()
    if not docs:
        return {"queued": 0, "message": "No documents eligible for indexing"}

    queued = 0
    for doc in docs:
        doc.parse_status = "pending"
        doc.parse_error = None
        queued += 1

    await db.commit()

    return {"queued": queued, "message": f"Queued {queued} document(s) for re-indexing"}


