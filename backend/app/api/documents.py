def _get_file_type(filename: str) -> str:
    return Path(filename).suffix.lower().lstrip(".")


@router.get("", response_model=list[DocumentResponse])
async def list_documents(
    project_id: int,
    db: AsyncSession = Depends(get_db),
    _: dict = Depends(require_viewer),
) -> list[DocumentResponse]:
    result = await db.execute(
        select(Document).where(Document.project_id == project_id).order_by(Document.created_at)
    )
    docs = result.scalars().all()

    # Build a map of assessment db_id → project_run_number for autogenerated docs
    assessment_ids = {d.source_assessment_id for d in docs if d.source_assessment_id}
    run_number_map: dict[int, int] = {}
    if assessment_ids:
        a_result = await db.execute(
            select(Assessment.id, Assessment.project_run_number)
            .where(Assessment.id.in_(assessment_ids))
        )
        run_number_map = {row[0]: row[1] for row in a_result.fetchall()}

    # Attach run number to each doc as a transient attribute for the response
    out = []
    for doc in docs:
        d = DocumentResponse.model_validate(doc)
        if doc.source_assessment_id and doc.source_assessment_id in run_number_map:
            d.source_assessment_run_number = run_number_map[doc.source_assessment_id]
        out.append(d)
    return out


@router.get("/processing-progress")
async def get_processing_progress(
    project_id: int,
    db: AsyncSession = Depends(get_db),
    _: dict = Depends(require_viewer),
):
    """Return ingestion pipeline stage progress for all documents currently in 'processing' state.
    Returns {doc_id: {stage, stage_parse, stage_screen, stage_expand, stage_classify, stage_embed,
                       lines_parsed, lines_screened, evidence_units, units_classified, units_embedded, pct}}"""
    from app.models.orm import IngestionRun
    from sqlalchemy import desc

    processing_result = await db.execute(
        select(Document.id).where(
            Document.project_id == project_id,
            Document.parse_status == "processing",
        )
    )
    processing_ids = [row[0] for row in processing_result.fetchall()]
    if not processing_ids:
        return {}

    # Get the latest active run for each processing document
    progress = {}
    for doc_id in processing_ids:
        run_result = await db.execute(
            select(IngestionRun)
            .where(IngestionRun.document_id == doc_id, IngestionRun.status == "running")
            .order_by(desc(IngestionRun.started_at))
            .limit(1)
        )
        run = run_result.scalar_one_or_none()
        if not run:
            progress[doc_id] = {"stage": "parse", "pct": 0}
            continue

        # Map stages to completion percentage (each stage = 20%)
        stage_order = ["parse", "screen", "expand", "classify", "embed"]
        completed = sum(
            1 for s in ["stage_parse", "stage_screen", "stage_expand", "stage_classify", "stage_embed"]
            if getattr(run, s) == "complete"
        )
        pct = completed * 20

        progress[doc_id] = {
            "stage":         run.current_stage or "parse",
            "stage_parse":   run.stage_parse,
            "stage_screen":  run.stage_screen,
            "stage_expand":  run.stage_expand,
            "stage_classify":run.stage_classify,
            "stage_embed":   run.stage_embed,
            "lines_parsed":  run.lines_parsed,
            "lines_screened":run.lines_screened,
            "evidence_units":run.evidence_units_created,
            "units_classified":run.units_classified,
            "units_embedded":run.units_embedded,
            "pct":           pct,
        }
    return progress


