def _human_gap_detail(row: dict) -> str:
    missing_evidence = str(row.get("missing_evidence") or "").strip()
    if missing_evidence:
        return missing_evidence
    rationale = str(row.get("rationale") or "").strip()
    if rationale and not re.search(r"Bucket=|effective_support=|evidence_quality=|critical=true|weight=", rationale):
        return rationale
    objective_text = str(row.get("objective_text") or "").strip()
    if objective_text:
        return f"Evidence does not fully demonstrate: {objective_text}"
    return "Evidence does not fully demonstrate this objective."


def _build_gaps_from_objective_rows(objective_rows: list[dict], status: str) -> list[str]:
    gaps: list[str] = []
    for row in objective_rows or []:
        if str(row.get("status") or "") == "met":
            continue
        objective_id = str(row.get("objective_id") or "objective").strip()
        detail = _human_gap_detail(row)
        gaps.append(f"{objective_id} ({_objective_status_label(row.get('status'))}): {detail}")
    return gaps

