def evidence_scope_fingerprint(entries: list[dict[str, Any]]) -> str | None:
    """Hash the exact evidence files and ingestion runs approved for an assessment."""
    if not entries:
        return None
    normalized = sorted(entries, key=lambda item: int(item["document_id"]))
    return hashlib.sha256(
        json.dumps(normalized, sort_keys=True, separators=(",", ":")).encode("utf-8")
    ).hexdigest()


def is_legacy_unverified_ingestion(fallback_stages: Any) -> bool:
    """Recognize only the transition marker applied to pre-governance ingestion runs."""
    return set(fallback_stages or []) == {"legacy_fallback_detected"}


def is_assessment_ready_ingestion(run: IngestionRun) -> bool:
    """Return whether an ingestion run may enter a new frozen assessment scope."""
    return (
        run.status == "complete"
        and run.quality_status == "passed"
        and run.readiness_eligible
        and not is_legacy_unverified_ingestion(run.fallback_stages)
    )


def _unready_project_documents(document_runs: list[tuple[Any, Any | None]]) -> list[dict[str, Any]]:
    """Describe project evidence that cannot yet be frozen into an assessment scope."""
    indexed_statuses = {"complete", "indexed"}
    unready: list[dict[str, Any]] = []
    for document, run in document_runs:
        if document.parse_status in indexed_statuses and run is not None and run.status == "complete":
            continue
        unready.append(
            {
                "document_id": document.id,
                "filename": document.filename,
                "parse_status": document.parse_status,
                "run_id": run.id if run is not None else None,
                "run_status": run.status if run is not None else None,
                "error_stage": run.error_stage if run is not None else None,
                "error_message": run.error_message if run is not None else document.parse_error,
            }
        )
    return unready


def _resolve_objective_review_concurrency(llm) -> int:
    configured = max(2, min(8, int(settings.assessment_concurrency)))
    model = str(getattr(llm, "model", "") or "").strip().lower()
    provider_hint = type(llm).__name__.lower()

    if "ollama" in provider_hint:
        if "120b" in model or "405b" in model:
            return min(configured, 2)
        if "70b" in model or "72b" in model or "cloud" in model:
            return min(configured, 3)
        return min(configured, 4)

    if "claude" in provider_hint or "bedrock" in provider_hint:
        return min(configured, 4)

    return configured

