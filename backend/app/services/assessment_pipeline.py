def _triage_role(cls: EvidenceClassification | None, doc: Document) -> str:
    if doc.document_intent in {"documents_gaps", "evaluates"} and doc.document_type in {"audit_finding", "assessment_report", "other"}:
        return "contradictory"
    if doc.document_intent == "plans":
        return "partial"
    if cls and cls.evidence_strength == "insufficient":
        return "irrelevant"
    if cls and cls.evidence_strength == "weak":
        return "partial"
    return "supporting"


def _extract_objective_text(objective: str) -> tuple[str, str]:
    if ":" in objective:
        obj_id, text = objective.split(":", 1)
        return obj_id.strip(), text.strip()
    return objective.strip(), objective.strip()


def _normalize_objective_id(objective_id: str | None) -> str:
    value = str(objective_id or "").strip()
    leading_label = re.match(
        r"^\s*([A-Za-z]{2,3}-\d{1,2}(?:\(\d+\))?(?:[a-z])?(?:\.\d+)?\.?(?:\[[^\]]+\])?)(?=\s|:|-|$)",
        value,
    )
    if leading_label:
        return leading_label.group(1).strip()[:128]
    if ":" in value:
        value = value.split(":", 1)[0].strip()
    return value[:128]


def _objective_alias_key(objective_id: str | None) -> str:
    value = _normalize_objective_id(objective_id).upper()
    tokens = re.findall(r"[A-Z]+|\d+", value)
    normalized_tokens = [
        (token.lstrip("0") or "0") if token.isdigit() else token
        for token in tokens
    ]
    return "".join(normalized_tokens)


def _build_objective_id_aliases(objectives: list[str]) -> dict[str, str]:
    aliases: dict[str, str] = {}
    for objective in objectives:
        obj_id, objective_text = _extract_objective_text(objective)
        canonical_id = _normalize_objective_id(obj_id)
        if not canonical_id:
            continue
        candidates = {
            obj_id,
            canonical_id,
            objective,
            f"{obj_id}: {objective_text}" if objective_text else obj_id,
        }
        for candidate in candidates:
            key = _objective_alias_key(candidate)
            if key:
                aliases.setdefault(key, canonical_id)
    return aliases


def _canonical_objective_id(objective_id: str | None, aliases: dict[str, str]) -> str:
    normalized = _normalize_objective_id(objective_id)
    if not normalized:
        return ""
    key = _objective_alias_key(objective_id)
    if key and key in aliases:
        return aliases[key]
    normalized_key = _objective_alias_key(normalized)
    if normalized_key and normalized_key in aliases:
        return aliases[normalized_key]
    return normalized


def _packet_id(control_id: str, objective_id: str, packet: dict[str, Any]) -> str:
    """Stable objective-specific ID used to bind LLM citations to evidence packets."""
    control_part = re.sub(r"[^A-Za-z0-9]+", "-", control_id or "control").strip("-").upper()
    objective_part = re.sub(r"[^A-Za-z0-9]+", "-", objective_id or "objective").strip("-").upper()
    unit = packet.get("unit_id")
    doc = packet.get("document_id")
    if unit is not None or doc is not None:
        basis = f"d{doc or 'x'}-u{unit or 'x'}"
    else:
        raw = "|".join([
            str(packet.get("filename") or ""),
            str(packet.get("section_path") or ""),
            str(packet.get("content") or "")[:240],
        ])
        basis = hashlib.sha1(raw.encode("utf-8", errors="ignore")).hexdigest()[:12]
    return f"PKT-{control_part}-{objective_part}-{basis}"[:128]


def _dedupe_objectives(objectives: list[str]) -> list[str]:
    deduped: list[str] = []
    seen: set[str] = set()
    for objective in objectives:
        obj_id, _ = _extract_objective_text(objective)
        key = _normalize_objective_id(obj_id)
        if not key or key in seen:
            continue
        seen.add(key)
        deduped.append(objective)
    return deduped


def _objective_priority(result: dict[str, Any]) -> tuple[int, int, int]:
    met_rank = {
        "yes": 3,
        "partial": 2,
        "no": 1,
    }.get(result.get("met"), 0)
    has_quote = 1 if result.get("evidence_quote") else 0
    has_gap = 1 if result.get("gap") else 0
    return (met_rank, has_quote, has_gap)


def _dedupe_gap_analysis(gap_analysis: list[dict[str, Any]], objectives: list[str]) -> list[dict[str, Any]]:
    aliases = _build_objective_id_aliases(objectives)
    expected_order = []
    for objective in objectives:
        obj_id, _ = _extract_objective_text(objective)
        norm = _normalize_objective_id(obj_id)
        if norm:
            expected_order.append(norm)

    best_by_id: dict[str, dict[str, Any]] = {}
    extras: list[str] = []
    for item in gap_analysis:
        raw_obj_id = str(item.get("objective_id") or "").strip()
        obj_id = _canonical_objective_id(raw_obj_id, aliases)
        if not obj_id:
            continue
        normalized = {
            **item,
            "objective_id": obj_id,
        }
        if raw_obj_id and raw_obj_id != obj_id:
            normalized.setdefault("raw_objective_id", raw_obj_id)
        current = best_by_id.get(obj_id)
        if current is None or _objective_priority(normalized) > _objective_priority(current):
            best_by_id[obj_id] = normalized
        if obj_id not in expected_order and obj_id not in extras:
            extras.append(obj_id)

    ordered: list[dict[str, Any]] = []
    for obj_id in expected_order + extras:
        item = best_by_id.get(obj_id)
        if item:
            ordered.append(item)
    return ordered


def _extract_challenged_objectives(note: str | None) -> list[str]:
    if not note:
        return []
    match = re.search(r"\[Challenged objectives:\s*([^\]]+)\]", note)
    if not match:
        return []
    return [part.strip() for part in match.group(1).split(",") if part.strip()]


def _packet_score(packet: dict[str, Any], target_control_id: str) -> float:
    classification_confidence = packet.get("classification_confidence") or 0.5
    score = _STRENGTH_WEIGHT.get(packet.get("evidence_strength"), 0.25)
    score += classification_confidence * 0.35
    score += _SOURCE_WEIGHT.get(packet.get("source_type"), 0.0)
    score += _ARTIFACT_BONUS.get(packet.get("artifact_type"), 0.0)
    score += min(packet.get("token_count", 0) / 800.0, 0.18)

    intent = packet.get("document_intent")
    if intent == "implements":
        score += 0.08
    elif intent == "plans":
        score -= 0.2
    elif intent in {"documents_gaps", "evaluates"}:
        score -= 0.1

    if target_control_id in (packet.get("control_ids") or []):
        score += 0.35
    if target_control_id in (packet.get("enhancement_ids") or []):
        score += 0.4
    if any(enh.startswith(f"{target_control_id}(") for enh in (packet.get("enhancement_ids") or [])):
        score += 0.15

    return round(score, 4)


