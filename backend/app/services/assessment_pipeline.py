async def get_scope_evidence_readiness(project_id: int, db: AsyncSession) -> dict[str, Any]:
    """Build an assessment scope without letting newly degraded ingestion pass silently."""
    indexed_statuses = ("complete", "indexed")
    linked_provider_ids = (
        await db.execute(
            select(ProjectCommonProvider.provider_id).where(ProjectCommonProvider.project_id == project_id)
        )
    ).scalars().all()
    scope_conditions = [
        Document.project_id == project_id,
        Document.policy_library_id.is_not(None),
        Document.procedure_library_id.is_not(None),
    ]
    if linked_provider_ids:
        scope_conditions.append(Document.provider_id.in_(linked_provider_ids))

    latest_runs = (
        select(
            IngestionRun.document_id.label("document_id"),
            func.max(IngestionRun.id).label("run_id"),
        )
        .where(IngestionRun.status == "complete")
        .group_by(IngestionRun.document_id)
        .subquery()
    )
    rows = (
        await db.execute(
            select(Document, IngestionRun)
            .join(latest_runs, latest_runs.c.document_id == Document.id)
            .join(IngestionRun, IngestionRun.id == latest_runs.c.run_id)
            .where(
                Document.parse_status.in_(indexed_statuses),
                or_(*scope_conditions),
                or_(Document.autogenerated.is_(False), Document.evidence_eligible.is_(True)),
            )
        )
    ).all()

    # A project assessment must not silently freeze a partial upload set while
    # other project-owned documents are still queued, processing, or failed.
    # Shared libraries remain point-in-time sources: only their completed,
    # eligible documents enter the frozen scope, so unrelated library work does
    # not block this project.
    latest_project_runs = (
        select(
            IngestionRun.document_id.label("document_id"),
            func.max(IngestionRun.id).label("run_id"),
        )
        .group_by(IngestionRun.document_id)
        .subquery()
    )
    project_document_runs = (
        await db.execute(
            select(Document, IngestionRun)
            .outerjoin(latest_project_runs, latest_project_runs.c.document_id == Document.id)
            .outerjoin(IngestionRun, IngestionRun.id == latest_project_runs.c.run_id)
            .where(
                Document.project_id == project_id,
                or_(Document.autogenerated.is_(False), Document.evidence_eligible.is_(True)),
            )
        )
    ).all()
    unready = _unready_project_documents(project_document_runs)
    degraded = [
        {
            "document_id": document.id,
            "filename": document.filename,
            "run_id": run.id,
            "fallback_stages": run.fallback_stages or [],
        }
        for document, run in rows
        if (run.quality_status != "passed" or not run.readiness_eligible)
        and not is_legacy_unverified_ingestion(run.fallback_stages)
    ]
    legacy_unverified = [
        {
            "document_id": document.id,
            "filename": document.filename,
            "run_id": run.id,
            "fallback_stages": run.fallback_stages or [],
        }
        for document, run in rows
        if is_legacy_unverified_ingestion(run.fallback_stages)
    ]
    eligible_entries = sorted(
        (
            {
                "document_id": document.id,
                "file_hash": document.file_hash,
                "ingestion_run_id": run.id,
                "quality_status": run.quality_status,
                "legacy_unverified": is_legacy_unverified_ingestion(run.fallback_stages),
            }
            for document, run in rows
            if is_assessment_ready_ingestion(run)
        ),
        key=lambda item: item["document_id"],
    )
    eligible_ids = [entry["document_id"] for entry in eligible_entries]
    scope_fingerprint = evidence_scope_fingerprint(eligible_entries)
    return {
        "ready": bool(eligible_ids) and not degraded and not unready,
        "eligible_document_ids": eligible_ids,
        "eligible_document_count": len(eligible_ids),
        "eligible_documents": eligible_entries,
        "scope_fingerprint": scope_fingerprint,
        "degraded_documents": degraded,
        "unready_documents": unready,
        "unready_document_count": len(unready),
        "legacy_unverified_documents": legacy_unverified,
        "legacy_unverified_document_count": len(legacy_unverified),
    }


async def preload_evidence_index(
    project_id: int,
    scope_doc_ids: list[int],
    db: AsyncSession,
    max_packets_per_control: int | None = 120,
    scope_run_ids: list[int] | None = None,
) -> dict[str, list[dict[str, Any]]]:
    if not scope_doc_ids:
        return {}

    query = (
        select(EvidenceUnit, EvidenceClassification, Document)
        .join(Document, Document.id == EvidenceUnit.document_id)
        .outerjoin(EvidenceClassification, EvidenceClassification.unit_id == EvidenceUnit.id)
        .where(Document.id.in_(scope_doc_ids))
    )
    if scope_run_ids:
        query = query.where(EvidenceUnit.run_id.in_(scope_run_ids))
    else:
        latest_runs = (
            select(
                IngestionRun.document_id.label("document_id"),
                func.max(IngestionRun.id).label("run_id"),
            )
            .where(
                IngestionRun.status == "complete",
                IngestionRun.document_id.in_(scope_doc_ids),
            )
            .group_by(IngestionRun.document_id)
            .subquery()
        )
        query = query.join(latest_runs, latest_runs.c.run_id == EvidenceUnit.run_id)

    result = await db.execute(query)

    by_control: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for unit, cls, doc in result.all():
        control_ids = list((cls.control_ids if cls else None) or [])
        enhancement_ids = list((cls.enhancement_ids if cls else None) or [])
        target_keys = set(control_ids)
        for enh in enhancement_ids:
            target_keys.add(enh)
            target_keys.add(enh.split("(")[0])

        profile = normalize_autogenerated_profile(
            doc,
            cls.artifact_type if cls else None,
            cls.evidence_strength if cls else None,
            cls.evidence_language_type if cls else None,
        )

        packet = {
            "unit_id": unit.id,
            "document_id": doc.id,
            "content": unit.content,
            "filename": doc.filename or "Unknown",
            "document_type": doc.document_type or "other",
            "document_intent": doc.document_intent or "other",
            "date": doc.created_at.strftime("%Y-%m-%d") if doc.created_at else None,
            "source_type": _source_type_for_doc(doc, project_id),
            "artifact_type": profile["artifact_type"],
            "evidence_strength": profile["evidence_strength"],
            "evidence_language_type": profile["evidence_language_type"],
            "classification_confidence": cls.model_confidence if cls else 0.0,
            "classification_explanation": (cls.explanation or "") if cls else "",
            "section_path": unit.section_path,
            "token_count": unit.token_count or max(1, len(unit.content) // 4),
            "page_numbers": unit.page_numbers or [],
            "control_ids": control_ids,
            "enhancement_ids": enhancement_ids,
            "triage_role": _triage_role(cls, doc) if cls else "supporting",
        }

        all_item = dict(packet)
        all_item["relevance_score"] = float(all_item.get("classification_confidence") or 0.0)
        by_control["__all__"].append(all_item)

        if not target_keys:
            continue

        for key in target_keys:
            item = dict(packet)
            item["relevance_score"] = _packet_score(item, key)
            by_control[key].append(item)

    for key, packets in by_control.items():
        packets.sort(key=lambda item: item["relevance_score"], reverse=True)
        seen: set[tuple[int | None, int | None]] = set()
        deduped = []
        for item in packets:
            packet_key = (item.get("unit_id"), item.get("document_id"))
            if packet_key in seen:
                continue
            seen.add(packet_key)
            deduped.append(item)
            if max_packets_per_control is not None and len(deduped) >= max_packets_per_control:
                break
        by_control[key] = deduped

    return by_control


def _select_packets_for_assessment(
    packets: list[dict[str, Any]],
    max_supporting: int = 8,
    max_partial: int = 3,
    max_contradictory: int = 3,
    max_irrelevant: int = 1,
    max_tokens: int = 5200,
) -> list[dict[str, Any]]:
    selected: list[dict[str, Any]] = []
    total_tokens = 0
    for role, limit in (
        ("supporting", max_supporting),
        ("partial", max_partial),
        ("contradictory", max_contradictory),
        ("irrelevant", max_irrelevant),
    ):
        role_packets = [pkt for pkt in packets if pkt.get("triage_role") == role]
        role_packets = _pick_diverse_packets(role_packets, limit)
        for pkt in role_packets:
            pkt_tokens = pkt.get("token_count", 0)
            if selected and total_tokens + pkt_tokens > max_tokens:
                continue
            selected.append(pkt)
            total_tokens += pkt_tokens
    return selected


def _objective_supporting_citation(obj: dict[str, Any]) -> list[dict[str, Any]]:
    if not obj.get("evidence_quote"):
        return []
    return [{
        "source": obj.get("source") or "Assessment Evidence",
        "quote": obj.get("evidence_quote"),
        "relevance": obj.get("objective_id"),
    }]


async def _run_objective_totality_review(
    control_id: str,
    control_title: str,
    objective_maps: dict[str, dict[str, Any]],
    system_context: str,
    llm,
) -> list[dict[str, Any]]:
    ordered_maps = list(objective_maps.values())
    objective_call_semaphore = asyncio.Semaphore(_resolve_objective_review_concurrency(llm))

    async def evaluate_objective(objective_map: dict[str, Any]) -> dict[str, Any]:
        async with objective_call_semaphore:
            objective_reference = objective_map["objective_reference"]
            packets = objective_map["prompt_packets"] or objective_map["considered_packets"]
            result = await run_gap_analysis(
                control_id=control_id,
                control_title=control_title,
                objectives=[objective_reference],
                chunks=packets,
                system_context=system_context,
                llm=llm,
            )
            if result:
                row = result[0]
            else:
                objective_id, _objective_text = _extract_objective_text(objective_reference)
                row = {
                    "objective_id": objective_id,
                    "met": "no",
                    "evidence_quote": None,
                    "source": None,
                    "gap": "Unable to complete objective-level evidence adjudication.",
                }
            row["objective_evidence_summary"] = objective_map["evidence_summary"]
            return row

    results = await asyncio.gather(*[evaluate_objective(item) for item in ordered_maps]) if ordered_maps else []
    return list(results)


