def _source_type_for_doc(doc: Document, project_id: int) -> str:
    if doc.project_id == project_id:
        return "project"
    if doc.provider_id is not None:
        return "common_control"
    if doc.policy_library_id is not None:
        return "policy"
    if doc.procedure_library_id is not None:
        return "procedure"
