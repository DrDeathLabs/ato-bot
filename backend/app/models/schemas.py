# ── Control Overrides ─────────────────────────────────────────────────────────

class ControlOverrideRequest(BaseModel):
    applicability: str | None = Field(default=None)  # "applicable"|"not_applicable"|"inherited"|None
    applicability_rationale: str | None = None
    satisfied: bool | None = None
    satisfied_rationale: str | None = None
    risk_accepted: bool | None = None
    risk_acceptance_rationale: str | None = None
    risk_acceptance_expiry: datetime | None = None
    # Manual status override — protected from automated re-assessment
    manual_status: str | None = Field(default=None)
    manual_status_rationale: str | None = None
    clear_manual_status: bool = False  # set True to remove the override

    @field_validator("applicability")
    @classmethod
    def validate_applicability(cls, v):
        if v is not None and v not in {"applicable", "not_applicable", "inherited"}:
            raise ValueError("applicability must be applicable, not_applicable, inherited, or null")
        return v

    @field_validator("manual_status")
    @classmethod
    def validate_manual_status(cls, v):
        valid = {"compliant", "partially_compliant", "non_compliant", "not_applicable"}
        if v is not None and v not in valid:
            raise ValueError(f"manual_status must be one of {valid}")
        return v


