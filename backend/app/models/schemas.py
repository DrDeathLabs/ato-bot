# ── Assessments ───────────────────────────────────────────────────────────────

class AssessmentStartRequest(BaseModel):
    llm_provider: str = Field(default="ollama")
    llm_model: str | None = None
    context_strategy: str = Field(default="rag")
    ollama_num_ctx: int | None = Field(default=None, ge=2048, le=262144)
    skip_stage3: bool = Field(default=False)
    carry_forward_compliant: bool = Field(
        default=True,
        description="Carry forward compliant findings from the most recent assessment instead of re-testing them.",
    )

    @field_validator("llm_provider")
    @classmethod
    def validate_provider(cls, v: str) -> str:
        if v not in {"ollama", "claude", "bedrock"}:
            raise ValueError("llm_provider must be ollama, claude, or bedrock")
        return v

    @field_validator("context_strategy")
    @classmethod
    def validate_strategy(cls, v: str) -> str:
        if v not in {"rag", "full", "hybrid"}:
            raise ValueError("context_strategy must be rag, full, or hybrid")
        return v


class AssessmentResponse(BaseModel):
    id: int
    project_id: int
    project_run_number: int = 1
    policy_id: int | None = None
    policy_version: int | None = None
    name: str | None = None
    notes: str | None = None
    status: str
    llm_provider: str
    llm_model: str
    context_strategy: str
    controls_total: int
    controls_complete: int
    error_message: str | None
    started_at: datetime | None
    completed_at: datetime | None
    paused_at: datetime | None = None
    progress_detail: str | None = None
    skip_stage3: bool = False
    carry_forward_compliant: bool = True

    @property
    def run_duration_seconds(self) -> int | None:
        if self.started_at and self.completed_at:
            return int((self.completed_at - self.started_at).total_seconds())
        return None

    model_config = {"from_attributes": True}


